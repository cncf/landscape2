/// Logo that could not be prepared for an item.
#[derive(Debug, Clone, PartialEq)]
struct LogoFailure {
    /// Error found preparing or writing the logo.
    error: String,
    /// Identifier of the item using the logo.
    item_id: String,
    /// Logo file name, as set in the landscape data.
    logo: String,
}

/// Logos that could not be prepared, one entry per affected item.
type LogoFailures = Vec<LogoFailure>;

/// Raw content of the landscape sources, read once at the start of the build.
///
/// It is parsed to get the landscape models and written as is to the output
/// sources directory, so no source is fetched twice.
#[derive(Debug, Clone, PartialEq)]
struct RawSources {
    /// Landscape data file content.
    data: String,
    /// Landscape settings file content.
    settings: String,

    /// Landscape games file content, when provided.
    games: Option<String>,
    /// Landscape guide file content, when provided.
    guide: Option<String>,
}

impl RawSources {
    /// Read the raw content of the landscape sources set in the build
    /// arguments provided.
    async fn read(args: &BuildArgs) -> Result<Self> {
        // Read all the sources concurrently
        let (data, games, guide, settings) = tokio::try_join!(
            args.data_source.read_raw(),
            args.games_source.read_raw(),
            args.guide_source.read_raw(),
            args.settings_source.read_raw(),
        )?;

        // Check the required sources were provided
        let Some(data) = data else {
            bail!("data file or url not provided");
        };
        let Some(settings) = settings else {
            bail!("settings file or url not provided");
        };

        Ok(Self {
            data,
            settings,
            games,
            guide,
        })
    }
}

/// Build landscape website.
///
/// # Errors
/// Returns an error if required assets are missing, inputs are invalid, or any
/// data processing step fails.
#[instrument(skip_all)]
pub async fn build(args: &BuildArgs) -> Result<()> {
    info!("building landscape website..");
    let start = Instant::now();

    // Check required web assets are present
    check_web_assets()?;

    // Setup output directory, removing the files generated by previous builds
    setup_output_dir(&args.output_dir, &local_inputs(args))?;

    // Setup cache, and the HTTP client used to fetch logos, settings images
    // and CLOMonitor reports summaries
    let cache = Cache::new(args.cache_dir.as_deref())?;
    let http_client = new_http_client(HeaderMap::new())?;

    // Read the landscape sources and parse them
    let raw_sources = RawSources::read(args).await?;
    let mut landscape_data = parse_source(SourceKind::Data, &raw_sources.data, LandscapeData::new_from_yaml)?;
    let mut settings = parse_source(
        SourceKind::Settings,
        &raw_sources.settings,
        LandscapeSettings::new_from_yaml,
    )?;
    let games = raw_sources
        .games
        .as_deref()
        .map(|raw| parse_source(SourceKind::Games, raw, LandscapeGames::new_from_yaml))
        .transpose()?;
    let guide = raw_sources
        .guide
        .as_deref()
        .map(|raw| parse_source(SourceKind::Guide, raw, LandscapeGuide::new_from_yaml))
        .transpose()?;

    // Copy games data and guide to the output directory
    prepare_games_data(games.as_ref(), &landscape_data, &args.output_dir)?;
    prepare_guide(guide.as_ref(), &args.output_dir)?;

    // Prepare items logos and copy them to the output directory, reporting
    // the logos that could not be prepared (logos are best-effort)
    let logo_failures = prepare_items_logos(
        &http_client,
        &args.logos_source,
        &settings.logos_viewbox,
        &mut landscape_data,
        &args.output_dir,
    )
    .await;
    log_logo_failures(&logo_failures);

    // Fetch some settings images and update their urls to the local copy
    prepare_settings_images(&mut settings, &http_client, &args.output_dir).await?;

    // Collect data from external services
    let (crunchbase_data, github_data) = tokio::try_join!(
        collect_crunchbase_data(&cache, &landscape_data),
        collect_github_data(&cache, &landscape_data)
    )?;

    // Enrich landscape data with some extra information from the settings and
    // external services
    landscape_data.enrich(&settings, &crunchbase_data, &github_data);

    // Collect CLOMonitor reports summaries and copy them to the output directory
    collect_clomonitor_reports(
        &cache,
        &http_client,
        clomonitor::CLOMONITOR_API_URL,
        &mut landscape_data,
        &settings.foundation.to_lowercase(),
        &args.output_dir,
    )
    .await;

    // Generate API data files
    generate_api(
        &ApiSources {
            landscape_data: &landscape_data,
            settings: &settings,
        },
        &args.output_dir,
    )?;

    // Generate QR code
    let qr_code = generate_qr_code(&settings.url, &args.output_dir)?;

    // Generate datasets for web application
    let datasets = generate_datasets(
        &NewDatasetsInput {
            crunchbase_data: &crunchbase_data,
            github_data: &github_data,
            landscape_data: &landscape_data,
            now: Utc::now(),
            settings: &settings,
            games: games.as_ref(),
            guide: guide.as_ref(),
            qr_code: Some(&qr_code),
        },
        &args.output_dir,
    )?;

    // Render index, embed-item, and kiosk html files and write them to the
    // output dir
    render_index_html(
        settings.analytics.as_ref(),
        &datasets,
        settings.osano.as_ref(),
        &args.output_dir,
    )?;
    render_embed_item_html(&settings.colors, &args.output_dir)?;
    render_kiosk_html(
        &settings.foundation,
        &settings.url,
        &settings.colors,
        settings.images.as_ref().and_then(|images| images.favicon.as_deref()),
        &args.output_dir,
    )?;

    // Copy embed and web application assets files to the output directory
    copy_embed_assets(&args.output_dir)?;
    copy_webapp_assets(&args.output_dir)?;

    // Generate items.csv file
    generate_items_csv_file(&landscape_data, &args.output_dir)?;

    // Generate projects.* files
    generate_projects_files(&landscape_data, &args.output_dir)?;

    // Prepare landscape screenshot (in PNG and PDF formats)
    if let Some(width) = &settings.screenshot_width {
        prepare_screenshot(*width, settings.base_path.as_deref(), &args.output_dir).await?;
    }

    // Copy data sources files to the output directory
    copy_data_sources_files(args, &raw_sources)?;

    let duration = start.elapsed().as_secs_f64();
    info!("landscape website built! (took: {:.3}s)", duration);
    display_success_msg(&args.output_dir.to_string_lossy(), logo_failures.len());

    Ok(())
}

/// Check web assets are present, to make sure the web app has been built.
#[instrument(err)]
fn check_web_assets() -> Result<()> {
    debug!("checking web assets are present");

    if !WebappAssets::iter().any(|path| path.starts_with("assets/")) {
        bail!("web assets not found, please make sure they have been built");
    }

    Ok(())
}

/// Collect projects CLOMonitor reports summaries and copy them to the output
/// directory, setting the path of the copy in the corresponding items.
///
/// `foundation` must be lowercased. Reports summaries are best-effort: the
/// errors found are logged and the affected items keep no report summary.
#[instrument(skip_all)]
async fn collect_clomonitor_reports(
    cache: &Cache,
    http_client: &reqwest::Client,
    base_url: &str,
    landscape_data: &mut LandscapeData,
    foundation: &str,
    output_dir: &Path,
) {
    debug!("collecting clomonitor reports");

    // Fetch CLOMonitor reports summaries and copy them to the output directory
    let projects = landscape_data
        .items
        .iter()
        .filter_map(|item| Some((item.id.as_str(), item.clomonitor_name.as_deref()?)));
    let reports_summaries: HashMap<String, String> = stream::iter(projects)
        .map(|(item_id, project_name)| async move {
            // Fetch report summary
            let report_summary = match clomonitor::fetch_report_summary(
                cache,
                http_client,
                base_url,
                foundation,
                project_name,
            )
            .await
            {
                Ok(Some(report_summary)) => report_summary,
                Ok(None) => return None,
                Err(err) => {
                    error!(%err, foundation, project_name, "error fetching report summary");
                    return None;
                }
            };

            // Copy report summary to the output dir
            let file_name = clomonitor::report_summary_file_name(foundation, project_name);
            let path = format!("{IMAGES_PATH}/{file_name}");
            if let Err(err) = fs::write(output_dir.join(&path), report_summary) {
                error!(%err, file_name, "error writing report summary to file");
                return None;
            }

            Some((item_id.to_string(), path))
        })
        .buffer_unordered(CLOMONITOR_MAX_CONCURRENCY)
        .filter_map(future::ready)
        .collect()
        .await;

    // Update clomonitor_report_summary field in landscape items with the path
    // of the SVG image
    for item in &mut landscape_data.items {
        if let Some(report_summary) = reports_summaries.get(&item.id) {
            item.clomonitor_report_summary = Some(report_summary.clone());
        }
    }

    // Remove the expired report summaries cached for projects no longer used
    let project_names = landscape_data.items.iter().filter_map(|item| item.clomonitor_name.as_deref());
    if let Err(err) = clomonitor::prune_cached_report_summaries(cache, foundation, project_names) {
        warn!(%err, "error removing expired report summaries from cache");
    }

    debug!("done!");
}

/// Copy data sources files to the output directory.
///
/// Local files are copied, and the sources fetched from a url are written
/// from the raw content read at the start of the build.
#[instrument(skip_all, err)]
fn copy_data_sources_files(args: &BuildArgs, raw_sources: &RawSources) -> Result<()> {
    // Helper function to copy the data source file provided, or to write its
    // raw content when it was fetched from a url
    fn copy(src_file: Option<&Path>, raw: &str, dst_file: &Path) -> Result<()> {
        if let Some(src_file) = src_file {
            fs::copy(src_file, dst_file)
                .with_context(|| format!("error copying {} to {}", src_file.display(), dst_file.display()))?;
        } else {
            fs::write(dst_file, raw).with_context(|| format!("error writing {}", dst_file.display()))?;
        }
        Ok(())
    }

    debug!("copying data sources files to output directory");
    let sources_path = args.output_dir.join(SOURCES_PATH);

    // Landscape data
    copy(
        args.data_source.data_file.as_deref(),
        &raw_sources.data,
        &sources_path.join(DATA_FILE),
    )?;

    // Settings
    copy(
        args.settings_source.settings_file.as_deref(),
        &raw_sources.settings,
        &sources_path.join(SETTINGS_FILE),
    )?;

    // Guide
    if let Some(raw) = &raw_sources.guide {
        copy(
            args.guide_source.guide_file.as_deref(),
            raw,
            &sources_path.join(GUIDE_FILE),
        )?;
    }

    // Games data
    if let Some(raw) = &raw_sources.games {
        copy(
            args.games_source.games_file.as_deref(),
            raw,
            &sources_path.join(GAMES_FILE),
        )?;
    }

    Ok(())
}

/// Copy embed assets files to the output directory.
#[instrument(skip_all, err)]
fn copy_embed_assets(output_dir: &Path) -> Result<()> {
    debug!("copying embed assets to output directory");

    let copy_embed_asset = |path: &str, embedded_file: EmbeddedFile| -> Result<()> {
        let path = output_dir.join(EMBED_PATH).join(path);
        if let Some(parent_path) = path.parent() {
            fs::create_dir_all(parent_path)
                .with_context(|| format!("error creating directory {}", parent_path.display()))?;
        }
        fs::write(&path, &embedded_file.data).with_context(|| format!("error writing {}", path.display()))
    };

    for path in EmbedAssets::iter() {
        if let Some(embedded_file) = EmbedAssets::get(&path) {
            copy_embed_asset(&path, embedded_file)?;
        }
    }
    for path in EmbedItemAssets::iter() {
        if path == "embed-item.html" {
            // This file is a template that will be rendered later on
            continue;
        }
        if let Some(embedded_file) = EmbedItemAssets::get(&path) {
            copy_embed_asset(&path, embedded_file)?;
        }
    }

    Ok(())
}

/// Copy web application assets files to the output directory.
#[instrument(skip_all, err)]
fn copy_webapp_assets(output_dir: &Path) -> Result<()> {
    debug!("copying web application assets to output directory");

    for path in WebappAssets::iter() {
        if path == "index.html" {
            // This file is a template that will be rendered later on
            continue;
        }

        if let Some(embedded_file) = WebappAssets::get(&path) {
            let path = output_dir.join(path.as_ref());
            if let Some(parent_path) = path.parent() {
                fs::create_dir_all(parent_path)
                    .with_context(|| format!("error creating directory {}", parent_path.display()))?;
            }
            fs::write(&path, &embedded_file.data)
                .with_context(|| format!("error writing {}", path.display()))?;
        }
    }

    Ok(())
}

/// Display build success message, including how many logos failed (if any).
fn display_success_msg(output_dir: &str, logo_failures: usize) {
    let logo_failures_msg = if logo_failures > 0 {
        format!(
            "\n⚠️  {logo_failures} item logo(s) could not be prepared (see the warnings above), the affected items have no logo.\n"
        )
    } else {
        String::new()
    };
    println!(
        "\n✅ Landscape built successfully!
{logo_failures_msg}
You can see it in action by running the following command:

👉 landscape2 serve --landscape-dir {output_dir}
"
    );
}

/// Generate API data files and write them to API_PATH in the output directory.
#[instrument(skip_all, err)]
fn generate_api(input: &ApiSources, output_dir: &Path) -> Result<()> {
    debug!("generating api");

    let api = Api::new(input);
    let api_path = output_dir.join(API_PATH);

    // Write data files to output dir, creating their parent directories
    for (endpoint, data) in &api.endpoints {
        let path = api_path.join(endpoint);
        if let Some(parent_path) = path.parent() {
            fs::create_dir_all(parent_path)
                .with_context(|| format!("error creating directory {}", parent_path.display()))?;
        }
        fs::write(&path, data).with_context(|| format!("error writing {}", path.display()))?;
    }

    Ok(())
}

/// Generate datasets from the landscape data and settings, as well as from the
/// data collected from external services (GitHub, Crunchbase, etc). Some of
/// the datasets will be embedded in the index document, and the rest will be
/// written to the DATASETS_PATH in the output directory.
#[instrument(skip_all, err)]
fn generate_datasets(input: &NewDatasetsInput, output_dir: &Path) -> Result<Datasets> {
    debug!("generating datasets");

    let datasets = Datasets::new(input);
    let datasets_path = output_dir.join(DATASETS_PATH);

    // Base
    let path = datasets_path.join("base.json");
    fs::write(&path, serde_json::to_vec(&datasets.base)?)
        .with_context(|| format!("error writing {}", path.display()))?;

    // Embed
    for (key, view) in &datasets.embed.views {
        let path = datasets_path.join(format!("embed_{key}.json"));
        fs::write(&path, serde_json::to_vec(&view)?)
            .with_context(|| format!("error writing {}", path.display()))?;

        let view_full_dataset = prepare_view_full_dataset(&datasets.full, view);
        let path = datasets_path.join(format!("embed_full_{key}.json"));
        fs::write(&path, serde_json::to_vec(&view_full_dataset)?)
            .with_context(|| format!("error writing {}", path.display()))?;
    }

    // Full
    let path = datasets_path.join(FULL_DATASET_FILE);
    fs::write(&path, serde_json::to_vec(&datasets.full)?)
        .with_context(|| format!("error writing {}", path.display()))?;

    // Stats
    let path = datasets_path.join("stats.json");
    fs::write(&path, serde_json::to_vec(&datasets.stats)?)
        .with_context(|| format!("error writing {}", path.display()))?;

    Ok(datasets)
}

