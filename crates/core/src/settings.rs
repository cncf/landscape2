/// Deserialize the settings colors, using the default palette when the colors
/// key is present but empty (e.g. `colors: ~`, or all its entries commented
/// out), as `serde(default)` only covers a missing key.
fn deserialize_colors<'de, D>(deserializer: D) -> Result<Colors, D::Error>
where
    D: Deserializer<'de>,
{
    Ok(Option::<Colors>::deserialize(deserializer)?.unwrap_or_default())
}

