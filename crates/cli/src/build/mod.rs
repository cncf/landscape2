/// Prepare the logo provided and write it to the logos directory in the
/// output directory, using its digest (plus extension) as file name. Returns
/// the path of the logo relative to the output directory.
async fn prepare_item_logo(
    http_client: &reqwest::Client,
    logos_source: &LogosSource,
    logos_viewbox: &LogosViewbox,
    logo: &str,
    output_dir: &Path,
) -> Result<String> {
    // Prepare logo
    let logo = prepare_logo(http_client, logos_source, logos_viewbox, logo).await?;

    // Write logo to the output dir
    let path = format!("{LOGOS_PATH}/{}.{}", logo.digest, logo.extension);
    let output_path = output_dir.join(&path);
    fs::write(&output_path, &logo.data)
        .with_context(|| format!("error writing logo {}", output_path.display()))?;

    Ok(path)
}

/// Prepare items logos and copy them to the output directory, updating the
/// logo reference on each landscape item.
///
/// Each distinct logo is prepared once, and items sharing it point to the
/// same file. Logos are best-effort: the items whose logo could not be
/// prepared or written are left with an empty logo and returned as failures.
#[instrument(skip_all)]
async fn prepare_items_logos(
    http_client: &reqwest::Client,
    logos_source: &LogosSource,
    logos_viewbox: &LogosViewbox,
    landscape_data: &mut LandscapeData,
    output_dir: &Path,
) -> LogoFailures {
    debug!("preparing logos");

    // Prepare each distinct logo once and copy it to the output directory
    let distinct_logos: HashSet<&str> = landscape_data.items.iter().map(|item| item.logo.as_str()).collect();
    let logos: HashMap<String, Result<String, String>> = stream::iter(distinct_logos)
        .map(|logo| async move {
            let result = prepare_item_logo(http_client, logos_source, logos_viewbox, logo, output_dir)
                .await
                .map_err(|err| {
                    error!(%err, logo, "error preparing logo");
                    format!("{err:#}")
                });
            (logo.to_string(), result)
        })
        .buffer_unordered(PREPARE_LOGOS_MAX_CONCURRENCY)
        .collect()
        .await;

    // Update logo field in landscape items to logo digest path, leaving it
    // empty and tracking the failure when the logo could not be prepared
    let mut logo_failures = vec![];
    for item in &mut landscape_data.items {
        match logos.get(&item.logo) {
            Some(Ok(path)) => item.logo.clone_from(path),
            failed => {
                let error = match failed {
                    Some(Err(err)) => err.clone(),
                    _ => "logo not prepared".to_string(),
                };
                logo_failures.push(LogoFailure {
                    error,
                    item_id: item.id.clone(),
                    logo: mem::take(&mut item.logo),
                });
            }
        }
    }

    debug!("done!");
    logo_failures
}

/// Prepare landscape screenshot (in PNG and PDF formats).
///
/// The landscape just built is served on a port picked by the system, and the
/// screenshot is taken by a headless browser, in a blocking task as its API
/// is synchronous.
#[instrument(skip(output_dir), err)]
async fn prepare_screenshot(width: u32, base_path: Option<&str>, output_dir: &Path) -> Result<()> {
    debug!("preparing screenshot");

    // Check if Chrome/Chromium is available
    if browser::default_executable().is_err() {
        warn!("chrome/chromium not found, no screenshot will be taken");
        return Ok(());
    }

    // Launch server to serve landscape just built (the listener is bound
    // before navigating, so the server is ready to accept requests)
    let listener = TcpListener::bind("127.0.0.1:0").await.context("error binding screenshot server")?;
    let svr_addr = listener.local_addr().context("error getting screenshot server address")?;
    let server = tokio::spawn(serve::serve_with_listener(
        listener,
        serve::router(output_dir, base_path),
    ));

    // Take the screenshot in a blocking task
    let screenshot_url = format!("http://{svr_addr}/screenshot");
    let docs_path = output_dir.join(DOCS_PATH);
    let result = tokio::task::spawn_blocking(move || take_screenshot(width, &screenshot_url, &docs_path))
        .await
        .context("error running screenshot task")?;

    // Stop server, reporting its error when it stopped before the screenshot
    // was taken
    let result = match result {
        Err(err) if server.is_finished() => {
            let server_err = match server.await {
                Ok(Ok(())) => "server stopped".to_string(),
                Ok(Err(err)) => format!("{err:#}"),
                Err(err) => err.to_string(),
            };
            Err(err.context(format!("screenshot server stopped: {server_err}")))
        }
        result => {
            server.abort();
            result
        }
    };

    debug!("done!");
    result
}

/// Fetch some settings images, copy them to the output directory and update
/// their urls to the local copy.
///
/// Each image is written to `image_output_path(location)`, so images sharing
/// the same file name in different locations never overwrite each other.
#[instrument(skip_all, err)]
async fn prepare_settings_images(
    settings: &mut LandscapeSettings,
    http_client: &reqwest::Client,
    output_dir: &Path,
) -> Result<()> {
    // Helper function to process the image provided
    async fn process_image(
        location: Option<&str>,
        http_client: &reqwest::Client,
        output_dir: &Path,
    ) -> Result<Option<String>> {
        let Some(location) = location else {
            return Ok(None);
        };

        // Check the location ends in a file name with an extension, as the
        // output file name keeps it
        let img_path = image_output_path(location);
        if Path::new(&img_path).extension().is_none() {
            bail!("image location must end in a file name with an extension: {location}");
        }

        // Fetch image from url or local path
        let img = if Url::parse(location).is_ok() {
            let resp = http_client.get(location).send().await?;
            if resp.status() != StatusCode::OK {
                bail!(
                    "unexpected status ({}) code getting image {location}",
                    resp.status()
                );
            }
            resp.bytes().await?.to_vec()
        } else {
            fs::read(location).with_context(|| format!("failed to read image from path: {location}"))?
        };

        // Write image to output dir
        let output_path = output_dir.join(&img_path);
        fs::write(&output_path, img)
            .with_context(|| format!("error writing image {}", output_path.display()))?;

        Ok(Some(img_path))
    }

    debug!("preparing settings images");

    // Header
    if let Some(header) = &mut settings.header {
        header.logo = process_image(header.logo.as_deref(), http_client, output_dir).await?;
    }

    // Footer
    if let Some(footer) = &mut settings.footer {
        footer.logo = process_image(footer.logo.as_deref(), http_client, output_dir).await?;
    }

    // Other images
    if let Some(images) = &mut settings.images {
        images.favicon = process_image(images.favicon.as_deref(), http_client, output_dir).await?;
    }

    Ok(())
}

/// Prepare view full dataset creating a stripped down version of the full
/// dataset with only the data needed for the provided embed view.
fn prepare_view_full_dataset(full: &Full, view: &EmbedView) -> Full {
    // Items in the view
    let view_items_ids: HashSet<&str> = view.items.iter().map(|i| i.id.as_str()).collect();
    let items: Vec<Item> =
        full.items.iter().filter(|i| view_items_ids.contains(i.id.as_str())).cloned().collect();

    // Crunchbase and repositories urls of the items in the view
    let crunchbase_urls: HashSet<&str> = items.iter().filter_map(|i| i.crunchbase_url.as_deref()).collect();
    let repositories_urls: HashSet<&str> = items
        .iter()
        .flat_map(|i| i.repositories.iter().flatten())
        .map(|r| r.url.as_str())
        .collect();

    // Crunchbase and GitHub data of the items in the view
    let crunchbase_data: CrunchbaseData = full
        .crunchbase_data
        .iter()
        .filter(|(url, _)| crunchbase_urls.contains(url.as_str()))
        .map(|(url, org)| (url.clone(), org.clone()))
        .collect();
    let github_data: GithubData = full
        .github_data
        .iter()
        .filter(|(url, _)| repositories_urls.contains(url.as_str()))
        .map(|(url, repo_github_data)| (url.clone(), repo_github_data.clone()))
        .collect();

    Full {
        crunchbase_data,
        github_data,
        items,
    }
}

