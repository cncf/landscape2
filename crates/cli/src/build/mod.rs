/// Generate QR code and copy it to output directory.
#[instrument(skip(output_dir), err)]
fn generate_qr_code(url: &str, output_dir: &Path) -> Result<String> {
    debug!("generating qr code");

    // Generate QR code
    let code = qrcode::QrCode::new(url.as_bytes())?;
    let svg = code
        .render()
        .min_dimensions(200, 200)
        .dark_color(svg::Color("#000000"))
        .light_color(svg::Color("#ffffff"))
        .build();

    // Write QR code (SVG) to output dir
    let svg_path = Path::new(IMAGES_PATH).join(QR_CODE_FILE);
    let path = output_dir.join(&svg_path);
    fs::write(&path, svg).with_context(|| format!("error writing {}", path.display()))?;

    Ok(svg_path.to_string_lossy().into_owned())
}

/// Build the JSON-LD structured data of the index document: the website
/// information and the breadcrumb list of its main sections.
fn index_json_ld(base: &Base) -> serde_json::Value {
    // Prepare the breadcrumb list, including the guide only when available
    let name = format!("{} Landscape", base.foundation);
    let mut breadcrumbs = vec![
        json!({"@type": "ListItem", "position": 1, "name": "Explore", "item": format!("{}/", base.url)}),
        json!({"@type": "ListItem", "position": 2, "name": "Stats", "item": format!("{}/stats", base.url)}),
    ];
    if !base.guide_summary.is_empty() {
        breadcrumbs.push(
            json!({"@type": "ListItem", "position": 3, "name": "Guide", "item": format!("{}/guide", base.url)}),
        );
    }

    json!({
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": "WebSite",
                "name": name,
                "description": base.description.as_deref().unwrap_or(&name),
                "url": base.url,
            },
            {
                "@type": "BreadcrumbList",
                "itemListElement": breadcrumbs,
            },
        ],
    })
}

