/// Setup output directory, creating it when needed, removing the files
/// generated by previous builds and recreating the managed subdirectories.
///
/// Only the managed subdirectories and root files are removed, so other files
/// in the output directory (e.g. `CNAME`) are kept. The local inputs provided
/// cannot be located inside a managed subdirectory, as they would be removed.
#[instrument(skip(inputs), err)]
fn setup_output_dir(output_dir: &Path, inputs: &[&Path]) -> Result<()> {
    debug!("setting up output directory");

    // Create the output directory when needed
    fs::create_dir_all(output_dir)
        .with_context(|| format!("error creating output directory {}", output_dir.display()))?;
    let canonical_output_dir = fs::canonicalize(output_dir)
        .with_context(|| format!("error resolving output directory {}", output_dir.display()))?;

    // Refuse local inputs located inside a managed subdirectory
    let managed_paths: Vec<PathBuf> = MANAGED_PATHS
        .iter()
        .map(|path| {
            fs::canonicalize(output_dir.join(path)).unwrap_or_else(|_| canonical_output_dir.join(path))
        })
        .collect();
    for input in inputs {
        let Ok(canonical_input) = fs::canonicalize(input) else {
            continue;
        };
        if let Some(managed_path) = managed_paths.iter().find(|path| canonical_input.starts_with(path)) {
            bail!(
                "input {} is inside the output subdirectory {}, which is removed on every build",
                input.display(),
                managed_path.display()
            );
        }
    }

    // Remove the files generated by previous builds
    let managed = MANAGED_PATHS.iter().chain(MANAGED_FILES.iter()).map(|path| output_dir.join(path));
    for path in managed {
        let metadata = match fs::symlink_metadata(&path) {
            Ok(metadata) => metadata,
            Err(err) if err.kind() == io::ErrorKind::NotFound => continue,
            Err(err) => return Err(err).with_context(|| format!("error accessing {}", path.display())),
        };
        info!(path = %path.display(), "removing output from previous build");
        if metadata.is_dir() {
            fs::remove_dir_all(&path)
        } else {
            fs::remove_file(&path)
        }
        .with_context(|| format!("error removing {}", path.display()))?;
    }

    // Recreate the managed subdirectories
    for path in MANAGED_PATHS {
        let path = output_dir.join(path);
        fs::create_dir(&path).with_context(|| format!("error creating {}", path.display()))?;
    }

    Ok(())
}

/// Take the landscape screenshot from the url provided using a headless
/// browser, and write it in PNG and PDF formats to the docs directory
/// provided.
#[allow(clippy::cast_precision_loss)]
fn take_screenshot(width: u32, screenshot_url: &str, docs_path: &Path) -> Result<()> {
    // Setup headless browser and navigate to screenshot url
    let options = LaunchOptions {
        args: vec![
            OsStr::new("--force-device-scale-factor=2"),
            OsStr::new("--headless=new"),
            OsStr::new("--hide-scrollbars"),
        ],
        idle_browser_timeout: SCREENSHOT_TIMEOUT,
        sandbox: false,
        window_size: Some((width, 500)),
        ..Default::default()
    };
    let browser = Browser::new(options).context("error launching headless browser")?;
    let tab = browser.new_tab().context("error opening browser tab")?;
    tab.set_default_timeout(SCREENSHOT_TIMEOUT);
    tab.navigate_to(screenshot_url)
        .and_then(|tab| tab.wait_until_navigated())
        .with_context(|| format!("error navigating to screenshot url {screenshot_url}"))?;
    trace!("navigated to screenshot url");

    // Take screenshot in PNG format and save it to a file
    let png_b64_data = tab
        .call_method(Page::CaptureScreenshot {
            format: Some(CaptureScreenshotFormatOption::Png),
            quality: None,
            clip: None,
            from_surface: None,
            capture_beyond_viewport: Some(true),
            optimize_for_speed: None,
        })
        .context("error generating screenshot in png format")?
        .data;
    let png_data = b64.decode(png_b64_data)?;
    let png_path = docs_path.join("landscape.png");
    fs::write(&png_path, png_data).with_context(|| format!("error writing {}", png_path.display()))?;
    trace!("screenshot in png format ready");

    // Take screenshot in PDF format and save it to a file
    // We use the dimensions of the screenshot in PNG format to calculate the
    // dimensions of the PDF paper, converting from pixels to inches.
    let png_size = imagesize::size(&png_path).context("error getting screenshot in png format dimensions")?;
    let pdf_data = tab
        .print_to_pdf(Some(PrintToPdfOptions {
            margin_bottom: Some(0.0),
            margin_left: Some(0.0),
            margin_right: Some(0.0),
            margin_top: Some(0.0),
            page_ranges: Some("1".to_string()),
            paper_height: Some((png_size.height + 10) as f64 / 2.0 * 0.010_416_666_7),
            paper_width: Some(png_size.width as f64 / 2.0 * 0.010_416_666_7),
            print_background: Some(true),
            ..Default::default()
        }))
        .context("error generating screenshot in pdf format")?;
    let pdf_path = docs_path.join("landscape.pdf");
    fs::write(&pdf_path, pdf_data).with_context(|| format!("error writing {}", pdf_path.display()))?;
    trace!("screenshot in pdf format ready");

    Ok(())
}

/// Askama filters used by the index html template.
#[allow(
    clippy::inline_always,
    clippy::ref_option_ref,
    clippy::trivially_copy_pass_by_ref,
    clippy::unnecessary_wraps,
    clippy::unused_self
)]
mod filters {
    use landscape2_core::settings::Analytics;

    /// Filter to get the Google Tag Manager container ID from the analytics
    /// instance provided.
    #[askama::filter_fn]
    pub(crate) fn get_gtm_container_id(
        analytics: &Option<&Analytics>,
        _: &dyn askama::Values,
    ) -> askama::Result<Option<String>> {
        Ok(analytics.as_ref().and_then(|a| a.gtm.as_ref()).and_then(|gtm| gtm.container_id.clone()))
    }
}

