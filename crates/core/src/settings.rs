/// Landscape category.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Category {
    /// Name of the category overridden.
    pub name: CategoryName,
    /// Subcategories of the category, in the order they will be displayed.
    pub subcategories: Vec<SubcategoryName>,
}

/// Rule matching the items that belong to a category and, optionally, to
/// some of its subcategories.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct CategoryRule {
    /// Category the items must belong to.
    pub category: CategoryName,

    /// Subcategories the items must belong to. When not provided, all the
    /// subcategories of the category match. It cannot be empty.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub subcategories: Option<Vec<SubcategoryName>>,
}

impl CategoryRule {
    /// Check if the category and subcategory provided match this rule.
    pub(crate) fn matches(&self, category: &str, subcategory: &str) -> bool {
        self.category == category
            && self
                .subcategories
                .as_ref()
                .is_none_or(|subcategories| subcategories.iter().any(|sc| sc == subcategory))
    }

    /// Check the rule is valid.
    fn validate(&self) -> Result<()> {
        // Category
        if self.category.trim().is_empty() {
            bail!("category cannot be empty");
        }

        // Subcategories
        if let Some(subcategories) = &self.subcategories {
            if subcategories.is_empty() {
                bail!("subcategories cannot be empty (omit them to match all the subcategories)");
            }
            for (i, subcategory) in subcategories.iter().enumerate() {
                if subcategory.trim().is_empty() {
                    bail!("subcategory [{i}] cannot be empty");
                }
            }
        }

        Ok(())
    }
}

