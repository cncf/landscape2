/// Log a summary of the logos that could not be prepared (if any), with their
/// count and the first few of them.
fn log_logo_failures(logo_failures: &[LogoFailure]) {
    if logo_failures.is_empty() {
        return;
    }
    let first_logos = logo_failures
        .iter()
        .take(MAX_LISTED_LOGO_FAILURES)
        .map(|failure| format!("{} ({})", failure.logo, failure.item_id))
        .join(", ");
    warn!(
        count = logo_failures.len(),
        first = %first_logos,
        "some logos could not be prepared, the affected items have no logo"
    );
}

/// Parse the raw landscape source provided, logging the warnings found while
/// parsing it.
fn parse_source<T>(kind: SourceKind, raw: &str, parse: fn(&str) -> Result<Parsed<T>>) -> Result<T> {
    let Parsed { value, warnings } = parse(raw)?;
    for warning in &warnings {
        warn!(%kind, %warning, "landscape source warning");
    }
    Ok(value)
}

/// Copy the games data provided to the output directory, once checked that
